    @Test
    fun `import sqlite db csv and xlsx detects duplicates and records opening balances without fabricating history`(): Unit = runBlocking {
        val context = ApplicationProvider.getApplicationContext<Context>()
        val db = Room.inMemoryDatabaseBuilder(context, SmartDebtDatabase::class.java)
            .allowMainThreadQueries()
            .build()
        val settingsStore = SettingsDataStore(context)
        val backupMgr = BackupManager(db, settingsStore)
        val inspector = ExternalDbInspector(db, backupMgr)

        // 1. Create external SQLite DB mimicking "دفتر الحسابات"
        val extDbFile = File(context.cacheDir, "daftar_test.db").apply { delete() }
        val extSqlite = SQLiteDatabase.openOrCreateDatabase(extDbFile, null)
        extSqlite.execSQL("CREATE TABLE accounts (id INTEGER PRIMARY KEY, name TEXT, phone TEXT, balance REAL)")
        extSqlite.execSQL("INSERT INTO accounts (name, phone, balance) VALUES ('ياسين عبده', '778899001', 4500.0)")
        extSqlite.execSQL("INSERT INTO accounts (name, phone, balance) VALUES ('نادية حسن', '778899002', 2000.0)")
        extSqlite.close()

        val sqlInsp = inspector.inspectUri(context, Uri.fromFile(extDbFile)).getOrThrow()
        assertEquals(ImportFileFormat.SQLITE_DB, sqlInsp.format)
        assertEquals(2, sqlInsp.previewRows.size)
        val sqlReport = inspector.executeImport(context, sqlInsp, createSafetyBackup = false)
        assertEquals(2, sqlReport.importedCustomersCount)
        assertEquals(2, sqlReport.importedTransactionsCount)

        // Verify opening balance only (no fabricated transaction history)
        val yassin = db.customerDao().findByExactName("ياسين عبده")!!
        val yassinTx = db.transactionDao().getAllTransactionsOnce().filter { it.customerId == yassin.id }
        assertEquals(1, yassinTx.size)
        assertEquals(TransactionType.OPENING_BALANCE, yassinTx.first().type)
        assertEquals(4500.0, yassinTx.first().amount, 0.01)

        // 2. Import CSV with one duplicate ("ياسين عبده") and one new customer ("طارق سعيد")
        val csvFile = File(context.cacheDir, "customers_import.csv")
        csvFile.writeText(
            "اسم العميل,رقم الهاتف,إجمالي الديون,إجمالي المدفوعات\n" +
                "ياسين عبده,778899001,1000,0\n" +
                "طارق سعيد,774455661,3000,1000\n",
            Charsets.UTF_8,
        )
        val csvInsp = inspector.inspectUri(context, Uri.fromFile(csvFile)).getOrThrow()
        val csvReport = inspector.executeImport(context, csvInsp, createSafetyBackup = false)
        assertEquals(1, csvReport.importedCustomersCount)
        assertEquals(1, csvReport.skippedDuplicatesCount)
        val tariq = db.customerDao().getCustomerWithBalanceOnce(db.customerDao().findByExactName("طارق سعيد")!!.id)!!
        assertEquals(2000.0, tariq.balance, 0.01)

        // 3. Import genuine XLSX file generated by ExportManager
        val xlsxFile = File(context.cacheDir, "excel_import.xlsx")
        val exportMgr = ExportManager()
        val xlsxBytes = exportMgr.buildXlsxBytes(
            sheetTitle = "العملاء",
            headers = listOf("الاسم", "الهاتف", "الرصيد"),
            rows = listOf(listOf("مراد علي", "779900112", "8500")),
        )
        xlsxFile.writeBytes(xlsxBytes)
        val xlsxInsp = inspector.inspectUri(context, Uri.fromFile(xlsxFile)).getOrThrow()
        assertEquals(ImportFileFormat.XLSX, xlsxInsp.format)
        val xlsxReport = inspector.executeImport(context, xlsxInsp, createSafetyBackup = false)
        assertEquals(1, xlsxReport.importedCustomersCount)
        val murad = db.customerDao().getCustomerWithBalanceOnce(db.customerDao().findByExactName("مراد علي")!!.id)!!
        assertEquals(8500.0, murad.balance, 0.01)

        // 4. Import JSON client file
        val jsonFile = File(context.cacheDir, "clients_export.json")
        jsonFile.writeText(
            """[{"name":"عمر علي","phone":"770112233","balance":"3200"}]""",
            Charsets.UTF_8,
        )
        val jsonInsp = inspector.inspectUri(context, Uri.fromFile(jsonFile)).getOrThrow()
        assertEquals(ImportFileFormat.JSON, jsonInsp.format)
        val jsonReport = inspector.executeImport(context, jsonInsp, createSafetyBackup = false)
        assertEquals(1, jsonReport.importedCustomersCount)
        val omar = db.customerDao().getCustomerWithBalanceOnce(db.customerDao().findByExactName("عمر علي")!!.id)!!
        assertEquals(3200.0, omar.balance, 0.01)

        db.close()
        extDbFile.delete()
        csvFile.delete()
        xlsxFile.delete()
        jsonFile.delete()
        Unit
    }

    @Test
    fun `import multi-table WAL sqlite database from Muhasib Smart Pro preserves linked debts and payments without altering source`(): Unit = runBlocking {
        val context = ApplicationProvider.getApplicationContext<Context>()
        val db = Room.inMemoryDatabaseBuilder(context, SmartDebtDatabase::class.java)
            .allowMainThreadQueries()
            .build()
        val settingsStore = SettingsDataStore(context)
        val backupMgr = BackupManager(db, settingsStore)
        val inspector = ExternalDbInspector(db, backupMgr)

        val extDbFile = File(context.cacheDir, "muhasib_smart_pro.sqlite3").apply { delete() }
        val extSqlite = SQLiteDatabase.openOrCreateDatabase(extDbFile, null)
        extSqlite.enableWriteAheadLogging()
        extSqlite.execSQL("CREATE TABLE acc_customers (id INTEGER PRIMARY KEY, acc_name TEXT, mobile TEXT)")
        extSqlite.execSQL("CREATE TABLE acc_vouchers (id INTEGER PRIMARY KEY, customer_id INTEGER, type TEXT, amount REAL, notes TEXT)")
        extSqlite.execSQL("INSERT INTO acc_customers (id, acc_name, mobile) VALUES (10, 'مؤسسة الفجر', '776655443')")
        extSqlite.execSQL("INSERT INTO acc_vouchers (customer_id, type, amount, notes) VALUES (10, 'دين', 9000.0, 'بضاعة آجل')")
        extSqlite.execSQL("INSERT INTO acc_vouchers (customer_id, type, amount, notes) VALUES (10, 'سداد', 2500.0, 'دفعة أولى')")
        extSqlite.close()

        // Also delete companion -wal/-shm files to simulate user copying only the .sqlite3 file from a phone
        File("${extDbFile.absolutePath}-wal").delete()
        File("${extDbFile.absolutePath}-shm").delete()

        val origBytesBefore = extDbFile.readBytes()
        val insp = inspector.inspectUri(context, Uri.fromFile(extDbFile)).getOrThrow()
        assertEquals("المحاسب الذكي برو", insp.detectedSourceApp)
        assertEquals(2, insp.linkedTransactionsCount)
        assertEquals(1, insp.previewRows.size)
        assertEquals(9000.0, insp.previewRows.first().totalDebts, 0.01)
        assertEquals(2500.0, insp.previewRows.first().totalPayments, 0.01)

        val report = inspector.executeImport(context, insp, createSafetyBackup = false)
        assertEquals(1, report.importedCustomersCount)
        assertEquals(2, report.importedTransactionsCount)

        val cust = db.customerDao().getCustomerWithBalanceOnce(db.customerDao().findByExactName("مؤسسة الفجر")!!.id)!!
        assertEquals(9000.0, cust.totalDebts, 0.01)
        assertEquals(2500.0, cust.totalPayments, 0.01)
        assertEquals(6500.0, cust.balance, 0.01)

        // Original external SQLite file bytes must remain completely untouched
        assertTrue(origBytesBefore.contentEquals(extDbFile.readBytes()))

        db.close()
        extDbFile.delete()
        Unit
    }

