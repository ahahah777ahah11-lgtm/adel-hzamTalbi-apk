    @Test
    fun `backup creation validates integrity checksum and persists data across database reopen`(): Unit = runBlocking {
        val context = ApplicationProvider.getApplicationContext<Context>()
        val dbFile = context.getDatabasePath("test_persist_smart_debt.db")
        dbFile.delete()

        val db1 = Room.databaseBuilder(context, SmartDebtDatabase::class.java, "test_persist_smart_debt.db")
            .allowMainThreadQueries()
            .build()
        val repo1 = AccountingRepository(db1)
        val settingsStore = SettingsDataStore(context)
        val backupMgr1 = BackupManager(db1, settingsStore)

        val cid = (repo1.createCustomer("عميل الاستمرارية", "771231231", "ACC-900", 0.0, "") as com.example.data.local.AccountingResult.Success).data
        repo1.recordTransaction(cid, TransactionType.DEBT, 7500.0, "فاتورة أولى")
        repo1.recordTransaction(cid, TransactionType.PAYMENT, 2500.0, "دفعة أولى")

        val backupJson = backupMgr1.createBackupJsonString()
        val validation = backupMgr1.inspectBackupJson(backupJson)
        assertTrue(validation.isValid)
        assertTrue(validation.checksumVerified)
        assertEquals(1, validation.data!!.customers.size)
        assertEquals(2, validation.data!!.transactions.size)

        // Tampered backup must fail integrity check
        val tampered = backupJson.replace("عميل الاستمرارية", "اسم معدل")
        val tamperedValidation = backupMgr1.inspectBackupJson(tampered)
        assertFalse(tamperedValidation.isValid)

        db1.close()

        // Reopen database (simulating app restart) and verify data persisted
        val db2 = Room.databaseBuilder(context, SmartDebtDatabase::class.java, "test_persist_smart_debt.db")
            .allowMainThreadQueries()
            .build()
        val persistedCustomer = db2.customerDao().getCustomerWithBalanceOnce(cid)!!
        assertEquals("عميل الاستمرارية", persistedCustomer.name)
        assertEquals(5000.0, persistedCustomer.balance, 0.01)

        // Test restoring backup into clean database
        db2.debtsDao().deleteAll()
        db2.paymentsDao().deleteAll()
        db2.transactionDao().deleteAll()
        db2.customerDao().deleteAll()
        val backupMgr2 = BackupManager(db2, settingsStore)
        val restoreRes = backupMgr2.restoreFromValidatedBackup(validation)
        assertTrue(restoreRes.isSuccess)
        assertEquals(5000.0, db2.customerDao().getCustomerWithBalanceOnce(cid)!!.balance, 0.01)

        db2.close()
        dbFile.delete()
        Unit
    }

    @Test
    fun `export and restore native sqlite database file verifies quick_check integrity and preserves all records`(): Unit = runBlocking {
        val context = ApplicationProvider.getApplicationContext<Context>()
        val db = Room.inMemoryDatabaseBuilder(context, SmartDebtDatabase::class.java)
            .allowMainThreadQueries()
            .build()
        val repo = AccountingRepository(db)
        val settingsStore = SettingsDataStore(context)
        val backupMgr = BackupManager(db, settingsStore)

        val cid = (repo.createCustomer("شركة التصدير والاستعادة", "772233445", "ACC-SQL", 0.0, "") as com.example.data.local.AccountingResult.Success).data
        repo.recordTransaction(cid, TransactionType.DEBT, 12000.0, "بضاعة آجل")
        repo.recordTransaction(cid, TransactionType.PAYMENT, 4500.0, "دفعة نقدية")
        repo.addReminder(cid, "قسط مستحق", System.currentTimeMillis() + 3600_000L, 7500.0, "قبل الموعد")

        val exportedFile = File(context.cacheDir, "exported_smart_debt_test.db").apply { delete() }
        val exportRes = backupMgr.exportSqliteDatabaseToFile(context, exportedFile)
        assertTrue(exportRes.isSuccess)
        assertTrue(exportedFile.exists() && exportedFile.length() > 1024L)

        // Validate exported .db via PRAGMA quick_check
        val validation = backupMgr.inspectSqliteBackupFile(context, exportedFile)
        assertTrue(validation.isValid)
        assertTrue(validation.integrityOk)
        assertEquals(1, validation.customersCount)
        assertEquals(2, validation.transactionsCount)
        assertEquals(1, validation.remindersCount)

        // Wipe DB then restore from SQLite backup file
        db.reminderDao().deleteAll()
        db.debtsDao().deleteAll()
        db.paymentsDao().deleteAll()
        db.transactionDao().deleteAll()
        db.customerDao().deleteAll()
        assertEquals(0, db.customerDao().getAllCustomersOnce().size)

        val restoreRes = backupMgr.restoreFromValidatedSqliteBackup(context, validation)
        assertTrue(restoreRes.isSuccess)
        val restoredCust = db.customerDao().getCustomerWithBalanceOnce(cid)!!
        assertEquals("شركة التصدير والاستعادة", restoredCust.name)
        assertEquals(12000.0, restoredCust.totalDebts, 0.01)
        assertEquals(4500.0, restoredCust.totalPayments, 0.01)
        assertEquals(7500.0, restoredCust.balance, 0.01)
        assertEquals(1, db.reminderDao().getAllRemindersOnce().size)

        db.close()
        exportedFile.delete()
        Unit
    }
